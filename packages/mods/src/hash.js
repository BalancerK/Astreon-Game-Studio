// Content hashing that works in Node and in browsers (including pages that are not a secure context,
// where `crypto.subtle` does not exist). No imports, so it is safe to load anywhere.

/**
 * Deterministic JSON: object keys sorted, no whitespace. The same value always gives the same text, so the
 * same bundle always gives the same hash regardless of how it was written to disk.
 * Only plain JSON values are allowed (no undefined, functions, NaN, Infinity or cycles).
 * @param {any} value
 * @returns {string}
 */
export function canonicalJson(value) {
  if (value === null) return 'null';
  switch (typeof value) {
    case 'boolean': return value ? 'true' : 'false';
    case 'number':
      if (!Number.isFinite(value)) throw new TypeError('canonicalJson: numbers must be finite');
      return JSON.stringify(value);
    case 'string': return JSON.stringify(value);
    case 'object': {
      if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
      const keys = Object.keys(value).sort();
      return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalJson(value[k])}`).join(',')}}`;
    }
    default:
      throw new TypeError(`canonicalJson: unsupported type ${typeof value}`);
  }
}

