// Builds the studio's autocomplete data from the same JSDoc the API reference is made from: every package's public exports (functions, classes,
// constants) with a one-line description and signature, and the members of each class. The studio loads it only when completion is first used.
//   node tools/studio-api-index.js write    makes studio/app/data/api-index.js
//   node tools/studio-api-index.js check    fails if it is out of date (npm test runs this)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildModel } from './api-docs-lib.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'studio/app/data/api-index.js');

/** The first sentence of a description, trimmed to a length that fits a list. */
export function brief(text, max = 140) {
  const flat = String(text ?? '').replace(/\s+/g, ' ').trim();
  const sentence = /^(.+?[.!?])(\s|$)/.exec(flat)?.[1] ?? flat;
  return sentence.length > max ? `${sentence.slice(0, max - 1).trimEnd()}…` : sentence;
}

const KIND = { class: 'class', function: 'function', constant: 'constant', namespace: 'namespace', types: 'type' };

/** The compact index: { packages: { name: { description, exports: [{n, k, s, d, p, r, m}] } } }. */
export function buildIndex(base = root) {
  const model = buildModel(base);
  const packages = {};
  for (const pkg of model.packages) {
    const exports = [];
    for (const e of pkg.api) {
      if (e.doc?.internal) continue;
      const entry = { n: e.name, k: KIND[e.kind] ?? e.kind, s: e.signature ?? '', d: brief(e.doc?.description) };
      if (e.node) entry.node = 1;
      const params = (e.doc?.params ?? []).filter((p) => p.name && !p.name.includes('.'));
      if (params.length) entry.p = params.map((p) => [p.name, p.type ?? '', brief(p.description, 90)]);
      if (e.doc?.returns) entry.r = [e.doc.returns.type ?? '', brief(e.doc.returns.description, 90)];
      const members = (e.members ?? []).filter((m) => m.name !== 'constructor' && !m.name.startsWith('#') && !m.doc?.internal);
      if (members.length) entry.m = members.map((m) => ({ n: m.name, k: m.kind, s: m.signature ?? '', d: brief(m.doc?.description, 100) }));
      exports.push(entry);
    }
    packages[pkg.name] = { description: brief(pkg.description, 160), exports };
  }
  return { packages };
}

export function render(index) {
  return `// GENERATED by tools/studio-api-index.js from the packages' JSDoc: do not edit. Run \`node tools/studio-api-index.js write\` after changing the API.\n`
    + `export const API = ${JSON.stringify(index)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = render(buildIndex());
  const mode = process.argv[2] ?? 'write';
  if (mode === 'check') {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('studio/app/data/api-index.js is out of date. Run: node tools/studio-api-index.js write'); process.exit(1); }
    console.log(`studio/app/data/api-index.js is up to date (${(text.length / 1024).toFixed(0)} KB).`);
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, text);
    console.log(`Wrote studio/app/data/api-index.js (${(text.length / 1024).toFixed(0)} KB).`);
  }
}
